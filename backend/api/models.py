from django.contrib.auth.models import AbstractUser
from django.db import models


class User(AbstractUser):
    """Extended user with role (Manager or Staff)."""
    ROLE_CHOICES = [
        ('Manager', 'Manager'),
        ('Staff', 'Staff'),
    ]
    role = models.CharField(max_length=10, choices=ROLE_CHOICES, default='Staff')

    class Meta:
        db_table = 'User'


class FlockBatch(models.Model):
    """A flock batch brought onto the farm."""
    batch_id = models.AutoField(primary_key=True)
    user = models.ForeignKey(User, on_delete=models.CASCADE, db_column='user_id')
    breed_type = models.CharField(max_length=100)
    arrival_date = models.DateField()
    initial_population = models.PositiveIntegerField()

    class Meta:
        db_table = 'Flock_Batch'

    def __str__(self):
        return f"Batch {self.batch_id} - {self.breed_type}"


class DailyLog(models.Model):
    """Daily production log for a batch."""
    log_id = models.AutoField(primary_key=True)
    batch = models.ForeignKey(FlockBatch, on_delete=models.CASCADE, db_column='batch_id', related_name='daily_logs')
    record_date = models.DateField()
    feed_consumed_kg = models.FloatField(default=0.0)
    water_consumed_l = models.FloatField(default=0.0)
    mortality_count = models.PositiveIntegerField(default=0)
    eggs_small = models.PositiveIntegerField(default=0)
    eggs_medium = models.PositiveIntegerField(default=0)
    eggs_large = models.PositiveIntegerField(default=0)
    eggs_xl = models.PositiveIntegerField(default=0)
    eggs_reject = models.PositiveIntegerField(default=0)

    class Meta:
        db_table = 'Daily_Log'
        unique_together = ('batch', 'record_date')
        ordering = ['-record_date']

    @property
    def total_eggs(self):
        return (self.eggs_small + self.eggs_medium + self.eggs_large
                + self.eggs_xl)

    @property
    def total_eggs_with_reject(self):
        return self.total_eggs + self.eggs_reject

    def __str__(self):
        return f"Log {self.log_id} - Batch {self.batch_id} - {self.record_date}"


class AnomalyAlert(models.Model):
    """Anomaly alert generated by the detection engine."""
    SEVERITY_CHOICES = [
        ('Low', 'Low'),
        ('Medium', 'Medium'),
        ('High', 'High'),
        ('Critical', 'Critical'),
    ]
    ANOMALY_TYPES = [
        ('Egg_Drop', 'Egg Production Drop'),
        ('Mortality_Spike', 'Mortality Spike'),
        ('Feed_Anomaly', 'Feed Consumption Anomaly'),
        ('Water_Anomaly', 'Water Consumption Anomaly'),
    ]
    alert_id = models.AutoField(primary_key=True)
    batch = models.ForeignKey(FlockBatch, on_delete=models.CASCADE, db_column='batch_id', related_name='alerts')
    trigger_date = models.DateTimeField(auto_now_add=True)
    anomaly_type = models.CharField(max_length=30, choices=ANOMALY_TYPES)
    severity_level = models.CharField(max_length=10, choices=SEVERITY_CHOICES)
    acknowledged_status = models.BooleanField(default=False)
    description = models.TextField(blank=True, default='')

    class Meta:
        db_table = 'Anomaly_Alert'
        ordering = ['-trigger_date']

    def __str__(self):
        return f"Alert {self.alert_id} - {self.anomaly_type} - {self.severity_level}"
